import * as assert from 'assert/strict';
import * as fs from 'fs/promises';
import * as os from 'os';
import * as path from 'path';
import { createProjectConfigs } from '../configuration';
import { needsLegacyBuildRepair, writeProjectFiles } from '../projectFiles';

suite('Workspace configuration ownership', () => {
    const names = ['tasks.json', 'launch.json', 'c_cpp_properties.json'];
    const configs = (bin: string) => createProjectConfigs({
        toolchain: 'gnu', compilers: { c: path.join(bin, 'gcc.exe'), cpp: path.join(bin, 'g++.exe') },
        debugger: path.join(bin, 'gdb.exe'),
    }, '', false);
    let workspace: string;
    let dir: string;

    setup(async () => {
        workspace = await fs.mkdtemp(path.join(os.tmpdir(), 'nbcpp-project-'));
        dir = path.join(workspace, '.vscode');
        await fs.mkdir(dir);
    });
    teardown(async () => { await fs.rm(workspace, { recursive: true, force: true }); });

    async function installLegacyFixtures() {
        const oldRoot = path.join(workspace, 'old-extension');
        for (const name of names) {
            const raw = await fs.readFile(path.resolve(__dirname, '../../src/test/fixtures/1.4.1', name), 'utf8');
            const content = raw.replaceAll('C:\\\\Old NBCpp', JSON.stringify(oldRoot).slice(1, -1))
                .replaceAll('C:/Old NBCpp', oldRoot.replace(/\\/g, '/'));
            await fs.writeFile(path.join(dir, name), content);
        }
        return oldRoot;
    }

    test('unchanged generated files keep their timestamps and user edits survive a compiler change', async () => {
        await writeProjectFiles(workspace, configs('first-bin'));
        const paths = names.map(name => path.join(dir, name));
        for (const file of paths) {
            await fs.utimes(file, 1000, 1000);
        }
        await writeProjectFiles(workspace, configs('first-bin'));
        for (const file of paths) {
            assert.equal((await fs.stat(file)).mtimeMs, 1000000);
        }
        const customizedLaunch = (await fs.readFile(paths[1], 'utf8')) + '\n// Use my settings\n';
        await fs.writeFile(paths[1], customizedLaunch);
        await writeProjectFiles(workspace, configs('second-bin'));
        assert.match(await fs.readFile(paths[0], 'utf8'), /second-bin/);
        assert.match(await fs.readFile(paths[2], 'utf8'), /second-bin/);
        assert.equal(await fs.readFile(paths[1], 'utf8'), customizedLaunch);
    });

    test('custom build tasks and IntelliSense settings survive, without creating an unusable launch', async () => {
        const customTasks = '{ "tasks": [/* my custom task */] }';
        const customProperties = '{}';
        await fs.writeFile(path.join(dir, names[0]), customTasks);
        await fs.writeFile(path.join(dir, names[2]), customProperties);
        await writeProjectFiles(workspace, configs('bin'));
        assert.equal(await fs.readFile(path.join(dir, names[0]), 'utf8'), customTasks);
        assert.equal(await fs.readFile(path.join(dir, names[2]), 'utf8'), customProperties);
        await assert.rejects(fs.access(path.join(dir, names[1])), { code: 'ENOENT' });
    });

    test('stock 1.4.1 embedded files migrate together, including its unsigned IntelliSense file', async () => {
        const oldRoot = await installLegacyFixtures();
        assert.equal(await needsLegacyBuildRepair(workspace, 'Build C++'), true);
        assert.equal(await needsLegacyBuildRepair(workspace, 'Custom'), false);
        const oldBin = path.join(oldRoot, 'lldbv1.0', 'bin');
        await fs.mkdir(oldBin, { recursive: true });
        await fs.writeFile(path.join(oldBin, 'clang++.exe'), '');
        assert.equal(await needsLegacyBuildRepair(workspace, 'Build C++'), false);
        assert.equal(await needsLegacyBuildRepair(workspace, 'Build C'), true);

        await writeProjectFiles(workspace, configs('replacement'));
        for (const name of names) {
            const content = await fs.readFile(path.join(dir, name), 'utf8');
            assert.ok(content.startsWith('// Generated by NoBrainerCpp'));
            assert.doesNotMatch(content, /old-extension/);
        }
        assert.equal(await needsLegacyBuildRepair(workspace, 'Build C'), false);
    });

    test('even one modification to a 1.4.1 build task prevents automatic migration', async () => {
        await installLegacyFixtures();
        const file = path.join(dir, names[0]);
        const custom = (await fs.readFile(file, 'utf8')).replace('"-g"', '"-O2", "-g"');
        await fs.writeFile(file, custom);
        assert.equal(await needsLegacyBuildRepair(workspace, 'Build C'), false);
        await writeProjectFiles(workspace, configs('replacement'));
        assert.equal(await fs.readFile(file, 'utf8'), custom);
    });

    test('a moved compiler triggers repair only while the current task is unmodified', async () => {
        const bin = path.join(workspace, 'old-bin');
        await fs.mkdir(bin);
        await fs.writeFile(path.join(bin, 'gcc.exe'), '');
        await writeProjectFiles(workspace, configs(bin));
        assert.equal(await needsLegacyBuildRepair(workspace, 'Build C'), false);
        assert.equal(await needsLegacyBuildRepair(workspace, 'Build C++'), true);
        await fs.unlink(path.join(bin, 'gcc.exe'));
        assert.equal(await needsLegacyBuildRepair(workspace, 'Build C'), true);
        await fs.appendFile(path.join(dir, 'tasks.json'), '// Custom task settings\n');
        assert.equal(await needsLegacyBuildRepair(workspace, 'Build C'), false);
    });

    test('overlapping requests leave a complete configuration for the most recent toolchain', async () => {
        await Promise.all([writeProjectFiles(workspace, configs('first')), writeProjectFiles(workspace, configs('second'))]);
        for (const name of names) {
            const content = await fs.readFile(path.join(dir, name), 'utf8');
            assert.match(content, /second/);
            assert.doesNotMatch(content, /first/);
        }
        assert.deepEqual((await fs.readdir(dir)).sort(), [...names].sort());
    });

    test('migration resumes when only tasks.json was committed before an interruption', async () => {
        const replacement = configs('new-bin');
        await writeProjectFiles(workspace, replacement);
        const file = path.join(dir, 'tasks.json');
        const updatedTasks = await fs.readFile(file);
        await installLegacyFixtures();
        await fs.writeFile(file, updatedTasks);
        await writeProjectFiles(workspace, replacement);
        for (const name of names) {
            assert.match(await fs.readFile(path.join(dir, name), 'utf8'), /new-bin/);
        }
    });
});

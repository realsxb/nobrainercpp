import { createHash, randomUUID } from 'crypto';
import * as fs from 'fs/promises';
import * as path from 'path';
import type { createProjectConfigs } from './configuration';

type Configs = ReturnType<typeof createProjectConfigs>;
const header = '// Generated by NoBrainerCpp | SHA-256 ';

function digest(text: string) {
    return createHash('sha256').update(text.replace(/\r\n/g, '\n')).digest('hex');
}

function isManaged(content: string | undefined) {
    if (content === undefined) {
        return true;
    }
    const newline = content.indexOf('\n');
    return newline >= 0 && content.slice(0, newline).trimEnd() === header + digest(content.slice(newline + 1));
}

// 1.4.1 didn't sign its generated files. These hashes match its original
// embedded-toolchain output exactly, after replacing the install path with <extension>.
const legacyHashes = {
    tasks: '6116458e10d902c8ee0606631491d3870a9a9d9c0b8a402838e62d0d8dafd152',
    launch: '5c1655d72f7929321814c0f4625e843e8786dd8f519e598d6f7058a428b2dd9c',
    properties: '71aab79fbd4fedd8ca1d695c1c28370a1162409eb939432625e596df71d1917a',
};

function legacyInstallPath(content: string | undefined): string | undefined {
    const match = content?.match(/"(?:command|compilerPath)": ("(?:\\.|[^"\\])*")/);
    if (match) {
        try {
            const command: string = JSON.parse(match[1]);
            return command.match(/^(.*)[\\/]lldbv1\.0[\\/]bin[\\/]clang(?:\+\+)?\.exe$/i)?.[1];
        } catch {
            // User-authored JSONC need not be parseable by JSON.parse.
        }
    }
}

function isLegacyStock(content: string | undefined, key: keyof Configs, installPath: string | undefined) {
    if (!content || !installPath) {
        return false;
    }
    const escaped = JSON.stringify(installPath).slice(1, -1);
    const normalized = content.replaceAll(escaped, '<extension>').replaceAll(installPath.replace(/\\/g, '/'), '<extension>');
    return digest(normalized) === legacyHashes[key];
}

async function readFile(file: string) {
    try {
        return await fs.readFile(file, 'utf8');
    } catch (err) {
        if ((err as NodeJS.ErrnoException).code !== 'ENOENT') {
            throw err;
        }
    }
}

export async function needsLegacyBuildRepair(folderPath: string, label: string): Promise<boolean> {
    if (label !== 'Build C' && label !== 'Build C++') {
        return false;
    }
    const tasks = await readFile(path.join(folderPath, '.vscode', 'tasks.json'));
    if (!tasks) {
        return false;
    }
    let compiler: string;
    if (isManaged(tasks)) {
        const config: Configs['tasks'] = JSON.parse(tasks.slice(tasks.indexOf('\n') + 1));
        const task = config.tasks.find(item => item.label === label);
        if (!task || !path.isAbsolute(task.command)) {
            return false;
        }
        compiler = task.command;
    } else {
        const installPath = legacyInstallPath(tasks);
        if (!installPath || !isLegacyStock(tasks, 'tasks', installPath)) {
            return false;
        }
        compiler = path.join(installPath, 'lldbv1.0', 'bin', label === 'Build C' ? 'clang.exe' : 'clang++.exe');
    }
    try {
        await fs.access(compiler);
        return false;
    } catch (err) {
        const code = (err as NodeJS.ErrnoException).code;
        return code === 'ENOENT' || code === 'ENOTDIR';
    }
}

async function writeIfChanged(file: string, previous: string | undefined, config: Configs[keyof Configs]) {
    const body = JSON.stringify(config, null, 4) + '\n';
    const content = header + digest(body) + '\n' + body;
    if (content === previous?.replace(/\r\n/g, '\n')) {
        return true;
    }
    const temporary = file + '.' + randomUUID() + '.tmp';
    try {
        await fs.writeFile(temporary, content, { flag: 'wx' });
        if (previous === undefined) {
            // Publish a complete new file without replacing one another process
            // has just created. Volumes without hard links use the rename path.
            try {
                await fs.link(temporary, file);
                return true;
            } catch (err) {
                const code = (err as NodeJS.ErrnoException).code ?? '';
                if (code === 'EEXIST') { return false; }
                if (!['EPERM', 'ENOSYS', 'ENOTSUP', 'EOPNOTSUPP', 'EINVAL', 'UNKNOWN'].includes(code)) { throw err; }
            }
        }
        if (await readFile(file) === previous) {
            await fs.rename(temporary, file);
            return true;
        }
        return false;
    } finally {
        await fs.rm(temporary, { force: true });
    }
}

async function updateFiles(folderPath: string, configs: Configs) {
    const dir = path.join(folderPath, '.vscode');
    await fs.mkdir(dir, { recursive: true });
    const tasksFile = path.join(dir, 'tasks.json');
    const launchFile = path.join(dir, 'launch.json');
    const propertiesFile = path.join(dir, 'c_cpp_properties.json');
    const [tasks, launch, properties] = await Promise.all([tasksFile, launchFile, propertiesFile].map(readFile));
    const installPath = legacyInstallPath(tasks);
    const legacyTasks = isLegacyStock(tasks, 'tasks', installPath);
    // A custom tasks.json may define different labels. In that case F5 can use
    // its existing launch.json or the configuration provider for a new workspace.
    if (isManaged(tasks) || legacyTasks) {
        // Commit the compiler task before exposing a launch that references it.
        // Each subsequent file can be recognised even after a partial migration.
        if (!await writeIfChanged(tasksFile, tasks, configs.tasks)) {
            return;
        }
        if (isManaged(launch) || (launch && digest(launch) === legacyHashes.launch)) {
            await writeIfChanged(launchFile, launch, configs.launch);
        }
        if (isManaged(properties) || isLegacyStock(properties, 'properties', legacyInstallPath(properties))) {
            await writeIfChanged(propertiesFile, properties, configs.properties);
        }
    } else if (isManaged(properties)) {
        await writeIfChanged(propertiesFile, properties, configs.properties);
    }
}

const pending = new Map<string, Promise<void>>();

export async function writeProjectFiles(folderPath: string, configs: Configs): Promise<void> {
    const absolute = path.resolve(folderPath);
    const key = process.platform === 'win32' ? absolute.toLowerCase() : absolute;
    const previous = pending.get(key);
    const update = previous ? previous.catch(() => {}).then(() => updateFiles(folderPath, configs)) : updateFiles(folderPath, configs);
    pending.set(key, update);
    try {
        await update;
    } finally {
        if (pending.get(key) === update) {
            pending.delete(key);
        }
    }
}
